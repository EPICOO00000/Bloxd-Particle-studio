const seen = new Set();
const names = NAMES.trim().split(/\s+/).filter((name) => {
  // (a name that is a word of the Words tab too is there already, written the same)
  if (seen.has(name) || VOCAB_TEXTS.has(name)) return false;
  seen.add(name);
  return true;
}).sort((a, b) => (a < b ? -1 : 1));

export const NAME_SHAPES = names.map((name) => {
  noteBreaks(name);
  return drawnShape({
    id: `name-${slug(name)}`, name: `The name ${name}`, cat: 'names', sub: name[0], label: name, tags: `${name} name first text writing who`,
    draw: () => phrase(name), count: countFor(name),
  });
});

/** The headings of the Names tab: the first letters, in the order of the alphabet. */
export const NAME_HEADINGS = [...new Set(names.map((name) => name[0]))];
