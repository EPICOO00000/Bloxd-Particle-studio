// Pixel art: little pictures made of square dots, one particle for every dot.
//
// A picture is written row by row, the rows separated by "/": "#" is a dot and
// "." is empty. Pictures that are the same left and right are written as their
// left half up to and including the middle column (see `half`).
//
// "How many" works in steps: every dot is one particle, or a block of 2 x 2 or
// 3 x 3 of them, whichever fits the number asked for.

/** The whole picture from its left half; the last column of the half is the middle and is not repeated. */
const half = (text) => text.split('/').map((row) => row + [...row.slice(0, -1)].reverse().join('')).join('/');

function sprite(sub, id, name, text, tags) {
  const rows = text.split('/');
  const high = rows.length;
  const wide = Math.max(...rows.map((row) => row.length));
  const step = 2 / Math.max(wide, high);
  const dots = [];
  rows.forEach((row, r) => {
    for (let c = 0; c < row.length; c++) if (row[c] === '#') dots.push([c, r]);
  });
  const shape = {
    id: `px-${id}`, name, cat: 'pixel', sub, group: 'flat', tidy: true, count: dots.length, min: dots.length,
    gen: (n) => {
      const m = Math.max(1, Math.floor(Math.sqrt(n / dots.length)));
      const out = [];
      for (const [c, r] of dots) {
        for (let j = 0; j < m; j++) {
          for (let i = 0; i < m; i++) out.push([(c + (i + 0.5) / m - wide / 2) * step, (high / 2 - r - (j + 0.5) / m) * step, 0]);
        }
      }
      return out;
    },
  };
  shape.tags = `pixels 8-bit blocky retro${tags ? ` ${tags}` : ''}`;
  return shape;
}

